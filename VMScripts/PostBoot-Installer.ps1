# VM-side post-boot installation orchestrator for Enhanced-GPU-PV interactive mode.
# VM端后配置脚本，用于 Enhanced-GPU-PV 交互模式。
# This script is invoked via PowerShell Direct after the VM's first boot.
# 该脚本在 VM 首次启动后通过 PowerShell Direct 调用。

