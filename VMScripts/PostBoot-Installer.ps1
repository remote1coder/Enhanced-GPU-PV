    return [string]$gpus[0].FriendlyName
}

function Protect-XMLString {
    # Escape XML special characters / XML 实体转义
    param([string]$InputString)
    if ([string]::IsNullOrEmpty($InputString)) { return "" }
    $InputString = $InputString -replace '&', '&amp;'
    $InputString = $InputString -replace '<', '&lt;'
    $InputString = $InputString -replace '>', '&gt;'
    $InputString = $InputString -replace '"', '&quot;'
    $InputString = $InputString -replace "'", '&apos;'
    return $InputString
}

function Wait-ForService {
    param([string]$ServiceName, [int]$MaxSeconds = 60, [switch]$RequireRunning)
    $elapsed = 0
    while ($elapsed -lt $MaxSeconds) {
        $svc = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
        if ($svc -and (-not $RequireRunning -or $svc.Status -eq 'Running')) { return $svc }
        Start-Sleep -Seconds 2
        $elapsed += 2
    }
    return $null
}

function Wait-ForPnpDevice {
    param(
        [string]$Class = "Display",
        [string]$FriendlyNamePattern,
        [int]$MaxSeconds = 60
    )
    $elapsed = 0
    while ($elapsed -lt $MaxSeconds) {
        $dev = Get-PnpDevice -Class $Class -PresentOnly -ErrorAction Stop |
            Where-Object { $_.FriendlyName -match $FriendlyNamePattern -and $_.Status -eq 'OK' }
        if (@($dev).Count -gt 1) { throw 'Multiple matching devices were found; refusing ambiguous activation.' }
        if ($dev) { return $dev }
        Start-Sleep -Seconds 2
        $elapsed += 2
    }
    return $null
}

