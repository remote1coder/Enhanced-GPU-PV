        $results.Add((New-VerifiedComponentResult -Name $Config.AudioDriver -Verified ($audio.Count -gt 0) -InstallResult $InstallResults[$Config.AudioDriver]))
    }
    [pscustomobject]@{
        SchemaVersion=1; Success=$true
        RebootRequired=[bool](@($results | Where-Object { $_.RebootRequired }).Count -gt 0)
        Components=@($results.ToArray()); ManualActions=@($manual); StreamingVerified=$false
    }
}

