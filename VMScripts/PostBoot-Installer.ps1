    Write-Bilingual -En "Using Hardware ID: $vadHwId" -Zh "使用硬件 ID: $vadHwId"

    # Install via NefCon / 通过 NefCon 安装
    Write-Bilingual -En "Installing Virtual Audio Driver via NefCon..." -Zh "正在通过 NefCon 安装 Virtual Audio Driver..."
    $script:installResults.VirtualAudioDriver = Invoke-CheckedInstaller -StateDirectory $InstallersDir -BootSession $script:GuestBootSession -Name VirtualAudioDriver -FilePath $nefconExe.FullName -ArgumentList 'install', "`"$($vadInf.FullName)`"", $vadHwId, '--no-duplicates' -RebootCodes @(3010)

    # Wait for device / 等待设备出现
    Write-Bilingual -En "Waiting for Virtual Audio Driver device..." -Zh "等待 Virtual Audio Driver 设备..."
    $vadDev = Wait-ForPnpDevice -Class "MEDIA" -FriendlyNamePattern "Virtual Audio Driver" -MaxSeconds 30
    if ($vadDev) {
        Write-Bilingual -En "Virtual Audio Driver found: $($vadDev.FriendlyName)" -Zh "Virtual Audio Driver 已找到: $($vadDev.FriendlyName)"
        try {
            Enable-PnpDevice -InstanceId $vadDev.InstanceId -Confirm:$false -ErrorAction Stop | Out-Null
            Write-Bilingual -En "Virtual Audio Driver enabled." -Zh "Virtual Audio Driver 已启用。"
        }
        catch {
            throw "Enable device error: $_"
        }
    } else {
        throw "Virtual Audio Driver device not found after installation."
    }
}

