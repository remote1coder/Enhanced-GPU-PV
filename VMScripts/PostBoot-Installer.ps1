# Pure plan/schema helpers are intentionally separate from guest operations so
# tests can extract their ASTs without invoking this script's entrypoint.
function Get-PostBootPlan {
    param([Parameter(Mandatory=$true)][string]$StreamingChoice)
    $components = switch ($StreamingChoice) {
        'None'              { @() }
        'Parsec+ParsecVDA'   { 'Parsec'; 'ParsecVDA' }
        'Parsec+VDD'         { 'Parsec'; 'VDD' }
        'Sunshine+VDD'       { 'Sunshine'; 'VDD' }
        'Sunshine+ParsecVDA' { 'Sunshine'; 'ParsecVDA' }
        default { throw "Unsupported StreamingChoice: $StreamingChoice" }
    }
    [pscustomobject]@{
        Parsec = @($components) -contains 'Parsec'
        ParsecVDA = @($components) -contains 'ParsecVDA'
        Sunshine = @($components) -contains 'Sunshine'
        VDD = @($components) -contains 'VDD'
        Components = @($components)
    }
}

function Get-SunshineConfigLines {
    param($StreamConfig)
    # Verified against the upstream Windows configuration schema, 2026-10-11.
    # An absent output_name lets Sunshine choose its default display. A PnP
    # instance path is never a valid substitute for Sunshine's device_id.
    $hevc = '0'; $av1 = '0'; $hdr = 'disabled'; $bitrate = '50000'
    if ($StreamConfig) {
        if ($null -ne $StreamConfig.HEVCMode) { $hevc = [string]$StreamConfig.HEVCMode }
        if ($null -ne $StreamConfig.AV1Mode) { $av1 = [string]$StreamConfig.AV1Mode }
        if ($null -ne $StreamConfig.HDRMode) { $hdr = [string]$StreamConfig.HDRMode }
        if ($null -ne $StreamConfig.Bitrate) { $bitrate = [string]$StreamConfig.Bitrate }
    }
    if ($hevc -notmatch '^[0-3]$' -or $av1 -notmatch '^[0-3]$') { throw 'HEVCMode/AV1Mode must be 0, 1, 2 or 3.' }
    if ($hdr -notin @('auto','disabled')) { throw 'HDRMode must be auto or disabled; numeric legacy values require explicit migration.' }
    $parsedBitrate = 0
    if (-not [int]::TryParse($bitrate, [ref]$parsedBitrate) -or $parsedBitrate -lt 0) { throw 'Bitrate must be a nonnegative integer in Kbps.' }
    $lines = @('# Generated by Enhanced-GPU-PV; display and encoder default to Sunshine auto selection.',
        "hevc_mode = $hevc", "av1_mode = $av1", "dd_hdr_option = $hdr", "max_bitrate = $parsedBitrate")
    # dd_hdr_option has no effect when all display configuration is disabled.
    if ($hdr -eq 'auto') { $lines += 'dd_configuration_option = verify_only' }
    if ($StreamConfig -and -not [string]::IsNullOrWhiteSpace([string]$StreamConfig.OutputName)) {
        $displayId = [string]$StreamConfig.OutputName
        if ($displayId -notmatch '^\{[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\}$') {
            throw 'OutputName must be a Sunshine log device_id GUID, including braces.'
        }
        if ([string]$StreamConfig.OutputNameSource -ne 'SunshineLog') { throw 'An explicit OutputName requires OutputNameSource=SunshineLog; do not use a PnP instance ID.' }
        $lines += "output_name = $displayId"
    }
    return $lines
}



function Assert-SunshineConfiguration {
    param([string[]]$ActualLines,[string[]]$ExpectedLines)
    $actual=@{}; $expected=@{}
    foreach ($line in $ActualLines) {
        if ($line -match '^\s*(#|$)') { continue }
        $parts=$line -split '=',2
        if ($parts.Count -ne 2) { throw 'Sunshine configuration contains an invalid line.' }
        $key=$parts[0].Trim(); $value=$parts[1].Trim()
        if ($actual.ContainsKey($key)) { throw "Sunshine configuration contains duplicate key: $key" }
        $actual[$key]=$value
    }
    foreach ($line in $ExpectedLines) {
        if ($line -match '^\s*(#|$)') { continue }
        $parts=$line -split '=',2; $expected[$parts[0].Trim()]=$parts[1].Trim()
    }
    foreach ($key in $expected.Keys) {
        if (-not $actual.ContainsKey($key) -or $actual[$key] -cne $expected[$key]) { throw "Sunshine configuration does not match the selected plan: $key" }
    }
    foreach($automaticKey in @('output_name','encoder','dd_configuration_option')) {
        if (-not $expected.ContainsKey($automaticKey) -and $actual.ContainsKey($automaticKey)) { throw "Sunshine configuration unexpectedly overrides automatic selection: $automaticKey" }
    }
}

function Get-VerifiedGuestInstaller {
    param([string]$Name,$Config,[string]$Directory)
    $property=$Config.InstallerFiles.PSObject.Properties[$Name]
    if ($null -eq $property) { throw "Pinned package metadata is missing: $Name" }
    $entry=$property.Value;$fileName=[string]$entry.FileName
    if ($fileName -in @('.','..') -or $fileName -match '[. ]$') { throw 'Invalid package basename.' }
    if ([string]::IsNullOrWhiteSpace($fileName) -or [IO.Path]::GetFileName($fileName) -ne $fileName -or $fileName.IndexOfAny([IO.Path]::GetInvalidFileNameChars()) -ge 0) { throw 'Invalid package basename.' }
    if ([string]$entry.Sha256 -notmatch '^[A-Fa-f0-9]{64}$') { throw 'A pinned SHA256 is required for guest packages.' }
    $root=[IO.Path]::GetFullPath($Directory).TrimEnd('\')+'\'
    $path=[IO.Path]::GetFullPath((Join-Path $Directory $fileName))
    if (-not $path.StartsWith($root,[StringComparison]::OrdinalIgnoreCase)) { throw 'Package path escapes installer directory.' }
    $parent=Get-Item -LiteralPath $Directory -ErrorAction Stop
    if ($parent.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'Installer directory cannot be a reparse point.' }
    $file=Get-Item -LiteralPath $path -ErrorAction Stop
    if ($file.PSIsContainer -or ($file.Attributes -band [IO.FileAttributes]::ReparsePoint) -or $file.Length -le 0) { throw 'Package must be a nonempty regular file.' }
    $expectedSize=0L
    if (-not [long]::TryParse([string]$entry.Size,[ref]$expectedSize) -or $expectedSize -le 0) { throw 'Positive exact staged package size is required.' }
    if ($file.Length -ne $expectedSize) { throw "Package size mismatch: $Name" }
    if ((Get-FileHash -LiteralPath $path -Algorithm SHA256 -ErrorAction Stop).Hash -ine $entry.Sha256) { throw "Package SHA256 mismatch: $Name" }
    return $file
}
function Get-PinnedArchiveLayout {
    param([string]$Name, [string]$Version)
    switch ($Name) {
        'NefCon' {
            if ($Version -ne 'v1.17.40') { throw 'Unsupported NefCon layout version.' }
            return @{ Files=@('x64\nefconw.exe'); Executable='x64\nefconw.exe' }
        }
        'VDD' {
            if ($Version -ne '25.7.23') { throw 'Unsupported VDD layout version.' }
            return @{ Files=@('VirtualDisplayDriver\MttVDD.inf','VirtualDisplayDriver\mttvdd.cat','VirtualDisplayDriver\MttVDD.dll','VirtualDisplayDriver\vdd_settings.xml'); Inf='VirtualDisplayDriver\MttVDD.inf'; HardwareId='Root\MttVDD' }
        }
        'VirtualAudioDriver' {
            if ($Version -ne '25.7.23') { throw 'Unsupported VirtualAudioDriver layout version.' }
            return @{ Files=@('VirtualAudioDriver\VirtualAudioDriver.inf','VirtualAudioDriver\virtualaudiodriver.cat','VirtualAudioDriver\VirtualAudioDriver.sys'); Inf='VirtualAudioDriver\VirtualAudioDriver.inf'; HardwareId='ROOT\VirtualAudioDriver' }
        }
        'VBCable' {
            if ($Version -ne 'Pack43') { throw 'Unsupported VBCable layout version.' }
            return @{ Files=@('VBCABLE_Setup_x64.exe','vbMmeCable64_win7.inf','vbaudio_cable64_win7.cat','vbaudio_cable64_win7.sys'); Executable='VBCABLE_Setup_x64.exe' }
        }
        default { throw "No reviewed archive layout: $Name" }
    }
}

function Resolve-PinnedArchiveFiles {
    param([string]$Directory, $Layout)
    $root=[IO.Path]::GetFullPath($Directory).TrimEnd('\')
    $resolved=@{}
    foreach ($relative in $Layout.Files) {
        $path=[IO.Path]::GetFullPath((Join-Path $root $relative))
        if (-not $path.StartsWith($root+'\',[StringComparison]::OrdinalIgnoreCase)) { throw 'Archive member escapes extraction directory.' }
        $cursor=$path
        while ($true) {
            $item=Get-Item -LiteralPath $cursor -ErrorAction Stop
            if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'Archive member traverses a reparse point.' }
            if ($cursor -ieq $path) {
                if ($item.PSIsContainer -or $item.Length -le 0) { throw "Missing or empty archive member: $relative" }
                $resolved[$relative]=$item
            }
            if ($cursor -ieq $root) { break }
            $cursor=Split-Path -Parent $cursor
        }
    }
    return $resolved
}

function Get-VddSettingsModel {
    param($Config)
    $resolution='1920x1080'; $rate='60'; $hdr=$false; $gpu=''
    if ($Config.VDDConfig) {
        if ($null -ne $Config.VDDConfig.Resolution) { $resolution=[string]$Config.VDDConfig.Resolution }
        if ($null -ne $Config.VDDConfig.RefreshRate) { $rate=[string]$Config.VDDConfig.RefreshRate }
        if ($null -ne $Config.VDDConfig.HDR) {
            if ($Config.VDDConfig.HDR -isnot [bool]) { throw 'VDDConfig.HDR must be a JSON Boolean.' }
            $hdr=$Config.VDDConfig.HDR
        }
        $gpu=[string]$Config.VDDConfig.GPUFriendlyName
    }
    if ([string]::IsNullOrWhiteSpace($gpu)) { $gpu=[string]$Config.GPUFriendlyName }
    if ($gpu -match '[\r\n\x00]' -or $gpu -in @('AUTO','default')) { throw 'GPUFriendlyName must identify the selected guest adapter, not an automatic-selection token.' }
    if ($resolution -notmatch '^([1-9][0-9]*)x([1-9][0-9]*)$') { throw 'VDD Resolution must be WIDTHxHEIGHT using positive integers.' }
    $width=0; $height=0; $refresh=0
    if (-not [int]::TryParse($Matches[1],[ref]$width) -or -not [int]::TryParse($Matches[2],[ref]$height) -or -not [int]::TryParse($rate,[ref]$refresh) -or $refresh -le 0) { throw 'VDD mode exceeds supported positive integer configuration syntax.' }
    [pscustomobject]@{ Width=$width; Height=$height; RefreshRate=$refresh; HDR=$hdr; GPUFriendlyName=$gpu }
}

function New-VddSettingsXml {
    param($Model,[string]$GpuName)
    if ([string]::IsNullOrWhiteSpace($GpuName)) { throw 'An explicit, verified guest GPU name is required.' }
    $safeGpu=[Security.SecurityElement]::Escape($GpuName)
    $hdr=([string]$Model.HDR).ToLowerInvariant()
    # The schema is pinned to the 25.7.23 driver-only package, not latest main.
    return @"
<?xml version="1.0" encoding="utf-8"?>
<vdd_settings>
  <monitors><count>1</count></monitors>
  <gpu><friendlyname>$safeGpu</friendlyname></gpu>
  <global><g_refresh_rate>$($Model.RefreshRate)</g_refresh_rate></global>
  <resolutions><resolution><width>$($Model.Width)</width><height>$($Model.Height)</height><refresh_rate>$($Model.RefreshRate)</refresh_rate></resolution></resolutions>
  <options><CustomEdid>false</CustomEdid><PreventSpoof>false</PreventSpoof><EdidCeaOverride>false</EdidCeaOverride><HardwareCursor>true</HardwareCursor><SDR10bit>false</SDR10bit><HDRPlus>$hdr</HDRPlus><logging>false</logging><debuglogging>false</debuglogging></options>
</vdd_settings>
"@
}

function Get-VddSettingsPath {
    param($Model)
    # Upstream 25.7.23 uses this literal default, unless VDDPATH overrides it.
    $directory='C:\VirtualDisplayDriver'
    $key='HKLM:\SOFTWARE\MikeTheTech\VirtualDisplayDriver'
    if (Test-Path -LiteralPath $key) {
        $settings=Get-ItemProperty -LiteralPath $key -ErrorAction Stop
        if ($settings.VDDPATH -and ([string]$settings.VDDPATH).TrimEnd('\') -ine $directory) { throw 'Existing VDDPATH override requires explicit review; the script will not write an unrelated configuration path.' }
        # Upstream true/1 registry flags override XML. Do not silently alter them.
        $expected=@{ HDRPLUS=$Model.HDR; SDR10BIT=$false; CUSTOMEDID=$false; PREVENTMONITORSPOOF=$false; EDIDCEAOVERRIDE=$false; LOGS=$false; DEBUGLOGS=$false }
        foreach ($name in $expected.Keys) {
            if ([string]$settings.$name -in @('1','true') -and -not $expected[$name]) { throw "VDD registry override conflicts with selected XML settings: $name" }
        }
    }
    return (Join-Path $directory 'vdd_settings.xml')
}

function Assert-VddSettingsXml {
    param([string]$ActualXml,[string]$ExpectedXml)
    if ($ActualXml -match '<!DOCTYPE|<!ENTITY') { throw 'DTD/entity declarations are not allowed in VDD settings.' }
    [xml]$actual=$ActualXml; [xml]$expected=$ExpectedXml
    $paths=@('/vdd_settings/monitors/count','/vdd_settings/gpu/friendlyname','/vdd_settings/global/g_refresh_rate','/vdd_settings/resolutions/resolution/width','/vdd_settings/resolutions/resolution/height','/vdd_settings/resolutions/resolution/refresh_rate')
    $paths+=@($expected.vdd_settings.options.ChildNodes | ForEach-Object { '/vdd_settings/options/'+$_.Name })
    foreach($path in $paths) {
        $nodes=@($actual.SelectNodes($path)); $target=$expected.SelectSingleNode($path)
        if ($nodes.Count -ne 1 -or $nodes[0].InnerText -cne $target.InnerText) { throw "VDD XML does not match the selected configuration: $path" }
    }
}

function Assert-GuestPackageCompatibility {
    param($Plan,$Config,[int]$BuildNumber)
    if ($Config.AudioDriver -eq 'VirtualAudioDriver' -and $BuildNumber -lt 22000) { throw 'Pinned VirtualAudioDriver 25.7.23 requires Windows build 22000 or newer.' }
    if ($Plan.VDD -and (Get-VddSettingsModel $Config).HDR -and $BuildNumber -lt 22631) { throw 'Pinned VDD HDR requires Windows 11 23H2 (build 22631) or newer; choose SDR on older guests.' }
}

function Get-SunshineFirewallSpec {
    param([string]$ProgramPath)
    # Same program-scoped TCP/UDP policy as the pinned publisher firewall script.
    foreach($protocol in @('TCP','UDP')) {
        [pscustomobject]@{ Name="EasyGPUPV-Sunshine-$protocol"; Group='Easy-GPU-PV'; Protocol=$protocol; Program=$ProgramPath }
    }
}

function Assert-SunshineFirewallSnapshot {
    param($Spec,$Rule,$Port,$Application,$Address)
    $protocols=if($Spec.Protocol -eq 'TCP'){@('TCP','6')}else{@('UDP','17')}
    if (-not $Rule -or [string]$Rule.Name -cne $Spec.Name -or [string]$Rule.Group -cne $Spec.Group -or [string]$Rule.Enabled -ne 'True' -or [string]$Rule.Direction -ne 'Inbound' -or [string]$Rule.Action -ne 'Allow' -or [string]$Rule.Profile -notin @('Any','0')) { throw "Sunshine firewall rule properties differ: $($Spec.Name)" }
    if (-not $Port -or [string]$Port.Protocol -notin $protocols -or (@($Port.LocalPort) -join ',') -ne 'Any' -or (@($Port.RemotePort) -join ',') -ne 'Any') { throw 'Sunshine firewall protocol or port filter differs.' }
    if (-not $Application -or [string]$Application.Program -ine $Spec.Program) { throw 'Sunshine firewall program filter differs.' }
    if (-not $Address -or (@($Address.LocalAddress) -join ',') -ne 'Any' -or (@($Address.RemoteAddress) -join ',') -ne 'Any') { throw 'Sunshine firewall address filter differs.' }
}

function Assert-SunshineFirewall {
    param([string]$ProgramPath)
    foreach($spec in @(Get-SunshineFirewallSpec $ProgramPath)) {
        $rules=@(Get-NetFirewallRule -Name $spec.Name -PolicyStore ActiveStore -ErrorAction Stop)
        if ($rules.Count -ne 1) { throw "Expected one effective Sunshine firewall rule: $($spec.Name)" }
        $rule=$rules[0]
        $port=@(Get-NetFirewallPortFilter -AssociatedNetFirewallRule $rule -ErrorAction Stop)
        $app=@(Get-NetFirewallApplicationFilter -AssociatedNetFirewallRule $rule -ErrorAction Stop)
        $address=@(Get-NetFirewallAddressFilter -AssociatedNetFirewallRule $rule -ErrorAction Stop)
        if ($port.Count -ne 1 -or $app.Count -ne 1 -or $address.Count -ne 1) { throw 'Sunshine firewall filters could not be read unambiguously.' }
        Assert-SunshineFirewallSnapshot $spec $rule $port[0] $app[0] $address[0]
    }
}

function Initialize-SunshineFirewall {
    param([string]$ProgramPath)
    foreach($spec in @(Get-SunshineFirewallSpec $ProgramPath)) {
        $existing=@(Get-NetFirewallRule -Name $spec.Name -PolicyStore PersistentStore -ErrorAction SilentlyContinue)
        if ($existing.Count -eq 0) {
            New-NetFirewallRule -Name $spec.Name -DisplayName $spec.Name -Group $spec.Group -PolicyStore PersistentStore -Direction Inbound -Action Allow -Enabled True -Profile Any -Protocol $spec.Protocol -Program $spec.Program -LocalPort Any -RemotePort Any -LocalAddress Any -RemoteAddress Any -ErrorAction Stop | Out-Null
        }
    }
    # An existing conflicting rule is reported, never silently adopted or overwritten.
    Assert-SunshineFirewall $ProgramPath
}

function Get-VerifiedNefCon {
    param($Config,[string]$Directory)
    if ($script:VerifiedNefCon) { return $script:VerifiedNefCon }
    $package=Get-VerifiedGuestInstaller -Name NefCon -Config $Config -Directory $Directory
    $extract=Join-Path $Directory ('NefCon-'+[guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $extract -ErrorAction Stop | Out-Null
    Expand-Archive -LiteralPath $package.FullName -DestinationPath $extract -ErrorAction Stop
    $layout=Get-PinnedArchiveLayout -Name NefCon -Version $Config.InstallerFiles.NefCon.Version
    $files=Resolve-PinnedArchiveFiles -Directory $extract -Layout $layout
    $script:VerifiedNefCon=$files[$layout.Executable]; return $script:VerifiedNefCon
}

function Get-SunshineInstallerInvocation {
    param([string]$PackagePath, [string]$WindowsDirectory)
    $extension = [System.IO.Path]::GetExtension($PackagePath)
    if ($extension -eq '.msi') {
        [pscustomobject]@{
            FilePath = [System.IO.Path]::Combine($WindowsDirectory, 'System32\msiexec.exe')
            ArgumentList = @('/i', ('"' + $PackagePath + '"'), '/qn', '/norestart')
            RebootCodes = @(3010)
        }
    } elseif ($extension -eq '.exe') {
        [pscustomobject]@{ FilePath=$PackagePath; ArgumentList=@('/S'); RebootCodes=@() }
    } else { throw 'Unsupported Sunshine installer extension; expected .msi or .exe.' }
}

function Get-GuestBootSessionId {
    $os=@(Get-CimInstance -ClassName Win32_OperatingSystem -Property LastBootUpTime -ErrorAction Stop)
    if ($os.Count -ne 1 -or $os[0].LastBootUpTime -isnot [datetime]) { throw 'Guest boot session could not be determined.' }
    return $os[0].LastBootUpTime.ToUniversalTime().ToString('o',[Globalization.CultureInfo]::InvariantCulture)
}

function ConvertTo-GuestBootTime {
    param([string]$BootSession)
    $value=[datetimeoffset]::MinValue
    if (-not [datetimeoffset]::TryParseExact($BootSession,'o',[Globalization.CultureInfo]::InvariantCulture,[Globalization.DateTimeStyles]::None,[ref]$value) -or $value.Year -lt 2000) { throw 'Invalid guest boot session.' }
    return $value.UtcDateTime
}

function Get-PostBootRebootPath {
    param([string]$Directory,[string]$Name)
    if ($Name -cnotin @('VCRedist','Parsec','ParsecVDA','VDD','Sunshine','VBCable','VirtualAudioDriver')) { throw 'Unknown reboot journal component.' }
    $dir=Get-Item -LiteralPath $Directory -ErrorAction Stop
    if (-not $dir.PSIsContainer) { throw 'Reboot journal directory is not a directory.' }
    # Reject any junction/symlink ancestor before reading or writing the journal.
    $ancestor=$dir
    while ($null -ne $ancestor) {
        if ($ancestor.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'Reboot journal directory has a reparse point.' }
        $ancestor=$ancestor.Parent
    }
    $path=Join-Path $dir.FullName ('postboot-reboot.'+$Name+'.json')
    if (Test-Path -LiteralPath $path -ErrorAction Stop) {
        $file=Get-Item -LiteralPath $path -ErrorAction Stop
        if ($file.PSIsContainer -or ($file.Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw 'Reboot journal must be a regular file.' }
    }
    return $path
}

function Read-PostBootRebootRecord {
    param([string]$Directory,[string]$Name)
    $path=Get-PostBootRebootPath $Directory $Name
    if (-not (Test-Path -LiteralPath $path -PathType Leaf -ErrorAction Stop)) { return $null }
    $record=Get-Content -LiteralPath $path -Raw -Encoding UTF8 -ErrorAction Stop | ConvertFrom-Json -ErrorAction Stop
    if ($null -eq $record -or $record.SchemaVersion -isnot [int] -or $record.SchemaVersion -ne 1 -or $record.Name -cne $Name -or $record.State -cnotin @('InProgress','PendingReboot')) { throw "Invalid reboot journal: $path" }
    $null=ConvertTo-GuestBootTime $record.BootSession
    if ($record.State -ceq 'PendingReboot') {
        if ($record.ExitCode -isnot [int] -or ($record.ExitCode -ne 3010 -and -not ($Name -ceq 'VBCable' -and $record.ExitCode -eq 0))) { throw "Invalid pending reboot exit code: $path" }
    } elseif ($null -ne $record.ExitCode) { throw "Invalid in-progress reboot journal: $path" }
    return $record
}

function Write-PostBootRebootRecord {
    param([string]$Directory,[string]$Name,[string]$BootSession,[ValidateSet('InProgress','PendingReboot')][string]$State,$ExitCode=$null)
    $null=ConvertTo-GuestBootTime $BootSession
    $path=Get-PostBootRebootPath $Directory $Name
    $record=[ordered]@{SchemaVersion=1;Name=$Name;BootSession=$BootSession;State=$State;ExitCode=$ExitCode}
    $temp=$path+'.'+[guid]::NewGuid().ToString('N')+'.tmp'
    try {
        [IO.File]::WriteAllText($temp,($record|ConvertTo-Json -Depth 4),(New-Object Text.UTF8Encoding($false)))
        if ([IO.File]::Exists($path)) { [IO.File]::Replace($temp,$path,[System.Management.Automation.Language.NullString]::Value) } else { [IO.File]::Move($temp,$path) }
    } finally { if ([IO.File]::Exists($temp)) { [IO.File]::Delete($temp) } }
}

function Assert-PostBootRebootState {
    param([string]$Directory,[string]$BootSession)
    $boot=ConvertTo-GuestBootTime $BootSession
    foreach ($name in @('VCRedist','Parsec','ParsecVDA','VDD','Sunshine','VBCable','VirtualAudioDriver')) {
        $record=Read-PostBootRebootRecord $Directory $name
        if ($null -eq $record) { continue }
        if ($record.State -ceq 'InProgress') { throw "$name installer was interrupted or its result was not recorded. Inspect its installer log and the component state before manually clearing postboot-reboot.$name.json; reboot alone does not resolve an unknown result." }
        if ($boot -le (ConvertTo-GuestBootTime $record.BootSession)) { throw "$name requires a guest restart before continuing. A later Windows boot session has not been observed." }
    }
    # Read-only: a later boot allows component verification, never asserts it passed.
}

function Invoke-CheckedInstaller {
    param([string]$Name, [string]$FilePath, [string[]]$ArgumentList, [int[]]$RebootCodes = @(), [string]$StateDirectory, [string]$BootSession, [switch]$AlwaysReboot)
    foreach ($code in $RebootCodes) { if ($code -ne 3010) { throw 'Only the reviewed 3010 reboot exit code is supported.' } }
    if ($AlwaysReboot -and $Name -cne 'VBCable') { throw 'The mandatory publisher restart policy applies only to VBCable.' }
    if (-not (Test-Path -LiteralPath $FilePath -PathType Leaf)) { throw "$Name installer is missing: $FilePath" }
    $journal= -not [string]::IsNullOrWhiteSpace($StateDirectory)
    if ($journal) {
        Assert-PostBootRebootState -Directory $StateDirectory -BootSession $BootSession
        # Write before launch. An interrupted process or journal-write failure must
        # never turn a partly installed component into a successful skipped install.
        Write-PostBootRebootRecord $StateDirectory $Name $BootSession InProgress
    }
    $proc = Start-Process -FilePath $FilePath -ArgumentList $ArgumentList -Wait -PassThru -WindowStyle Hidden -ErrorAction Stop
    if ($null -eq $proc -or $null -eq $proc.ExitCode) { throw "$Name installer returned no exit code." }
    $exitCode = [int]$proc.ExitCode
    if ($exitCode -ne 0 -and $RebootCodes -notcontains $exitCode) { throw "$Name installer failed (exit code $exitCode). Inspect the failure before clearing its in-progress journal." }
    $reboot=($AlwaysReboot -or ($RebootCodes -contains $exitCode))
    if ($journal) {
        if ($reboot) {
            Write-PostBootRebootRecord $StateDirectory $Name $BootSession PendingReboot $exitCode
            throw "$Name installation requires a guest restart (exit $exitCode). The reboot journal was saved; this phase remains incomplete. Restart the guest before rerunning."
        }
        $path=Get-PostBootRebootPath $StateDirectory $Name
        [IO.File]::Delete($path)
    }
    [pscustomobject]@{ Name=$Name; ExitCode=$exitCode; RebootRequired=[bool]$reboot }
}

function New-VerifiedComponentResult {
    param([string]$Name, [bool]$Verified, $InstallResult)
    if (-not $Verified) {
        if ($InstallResult -and $InstallResult.RebootRequired) { throw "$Name requests a guest reboot (exit $($InstallResult.ExitCode)); installation is incomplete. Reboot before rerunning verification." }
        throw "$Name required postcondition is not satisfied. Installation is incomplete."
    }
    $exitCode = 0; $reboot = $false
    if ($InstallResult) { $exitCode = [int]$InstallResult.ExitCode; $reboot = [bool]$InstallResult.RebootRequired }
    [pscustomobject]@{ Name=$Name; Status='Installed'; Verified=$true; ExitCode=$exitCode; RebootRequired=$reboot }
}



function Get-RequiredVCRedistVersion {
    param($Config)
    $value = [string]$Config.VCRedistMinimumVersion
    if ([string]::IsNullOrWhiteSpace($value)) { $value = [string]$Config.InstallerFiles.VCRedist.Version }
    $version = $null
    if (-not [version]::TryParse($value.TrimStart('v','V'), [ref]$version) -or $version.Major -ne 14) {
        throw 'A pinned VCRedist v14 Version is required in InstallerFiles.VCRedist.Version (or VCRedistMinimumVersion).'
    }
    return $version
}

function Test-PostBootInstalledComponents {
